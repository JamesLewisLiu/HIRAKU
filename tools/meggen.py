"""Compile the XT446 synth card's MEG effect programs to C++ (PLAN.md section 14, Keyboardmania).

    tools/meggen.py RECORDING OUTDIR

RECORDING is what HK_MEG_RECORD=file appends while the card runs (third_party/mame swp30.cpp,
record_program()): per line a program's FNV-1a hash, the pipeline phase at its step 0 and its
384 instruction words, once the program has run unchanged for 256 samples. OUTDIR gets
hk_meg_programs.inc, which swp30.cpp includes: per program, run_prog<hash, phase>() is the 384
steps as step_fixed<D3, D2, PC, OPCODE, OPCODE[-3], OPCODE[-2]>() calls: the fields, and what the
steps before left in the delay slots, are compile-time constants; entered
at any step through a switch; and the table decode() looks programs up in. Without a recording the
table is empty and every program runs in the interpreter (step_decoded()).

The recording holds the firmware's programs, derived from the card's ROM: it lives under build/
and is never committed. Run on every build, this does nothing unless the output would change.
"""
import os
import sys

STEPS = 0x180


def fnv(words):
    h = 0xcbf29ce484222325
    for w in words:
        for b in range(8):
            h ^= (w >> (8 * b)) & 0xff
            h = (h * 0x100000001b3) & 0xffffffffffffffff
    return h


def read(path):
    progs = {}
    if not os.path.exists(path):
        return progs
    with open(path) as f:
        for n, line in enumerate(f, 1):
            t = line.split()
            if not t:
                continue
            h, k0, words = int(t[0], 16), int(t[1]), [int(w, 16) for w in t[2:]]
            if len(words) != STEPS or fnv(words) != h or not 0 <= k0 < 6:
                sys.exit(f'meggen: {path}:{n}: bad record')
            progs[(h, k0)] = words
    return progs


def emit(progs, source):
    out = [f'// Generated by tools/meggen.py from {os.path.basename(source)}: {len(progs)} program(s). Do not edit.\n']
    for (h, k0), words in sorted(progs.items()):
        out.append(f'template<> void swp30_device::meg_state::run_prog<0x{h:016x}ULL, {k0}>(s64 &p, int pc, int n)\n{{\n\tswitch(pc) {{\n')
        for pc, w in enumerate(words):
            k = (k0 + pc) % 6
            w3, w2 = words[(pc - 3) % STEPS], words[(pc - 2) % STEPS]   # their delay slots
            call = f'step_fixed<{k % 3}, {k % 2}, {pc}, 0x{w:x}ULL, 0x{w3:x}ULL, 0x{w2:x}ULL>(p);'
            tail = ' return;' if pc == STEPS - 1 else ' if(!--n) return; [[fallthrough]];'
            out.append(f'\tcase {pc}: {call}{tail}\n')
        out.append('\t}\n}\n\n')
    if progs:
        out.append('const swp30_device::meg_state::compiled_prog swp30_device::meg_state::s_programs[] = {\n')
        for (h, k0) in sorted(progs):
            out.append(f'\t{{0x{h:016x}ULL, {k0}, &swp30_device::meg_state::run_prog<0x{h:016x}ULL, {k0}>}},\n')
        out.append('};\n')
    else:
        out.append('const swp30_device::meg_state::compiled_prog swp30_device::meg_state::s_programs[1] = {};\n')
    out.append(f'const int swp30_device::meg_state::s_program_count = {len(progs)};\n')
    return ''.join(out)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    rec, outdir = sys.argv[1], sys.argv[2]
    text = emit(read(rec), rec)
    os.makedirs(outdir, exist_ok=True)
    path = os.path.join(outdir, 'hk_meg_programs.inc')
    if os.path.exists(path) and open(path).read() == text:
        return
    with open(path + '.tmp', 'w') as f:
        f.write(text)
    os.replace(path + '.tmp', path)
    print(f'meggen: {path}: {text.count("run_prog<") // 2} program(s)')


if __name__ == '__main__':
    main()
